static void test_public_hardware_vectors(void)
{
    /* The hardware suite's 2048-bit Habibi public key differs from retail's
     * final modulus word. For a consistent 1024-bit blob, Python's independent
     * pow(input,65537,modulus) gives the second expected output hash. */
    static const UCHAR expected[2][20] = {
        {0x1a,0x31,0x40,0xee,0x8e,0x0b,0x07,0xff,0x36,0xe3,0xb1,0x8e,0xc8,0x87,0xe2,0xd7,0xb1,0x63,0x01,0xe4},
        {0x92,0x93,0xf1,0x63,0xe3,0xfa,0x01,0xa2,0x60,0x2e,0x98,0xcb,0xbf,0xe8,0x34,0x89,0xe6,0x9c,0x45,0xc6}
    };
    UCHAR key[sizeof retail_key], input[264] = {0}, output[264], hash[20];
    ULONG bits, capacity;
    XBOX_SHA_CONTEXT sha;
    unsigned i;
    memcpy(key, retail_key, sizeof key);
    memcpy(key + 272, "\x6b\x90\x9c\x89", 4);
    memcpy(input, "Encrypt me", 10);
    for (i = 0; i < 2; i++) {
        bits = i ? 1024 : 2048;
        memcpy(key + 8, &bits, 4);
        capacity = bits / 8 + 8;
        memcpy(key + 4, &capacity, 4);
        memset(output, 0, sizeof output);
        CHECK(xbox_XcPKEncPublic(key, input, output));
        xbox_XcSHAInit(&sha);
        xbox_XcSHAUpdate(&sha, output, sizeof output);
        xbox_XcSHAFinal(&sha, hash);
        CHECK(!memcmp(hash, expected[i], sizeof hash));
    }
    /* The hardware suite also passes a mismatched 1024-bit header with a
     * 264-byte modulus buffer. Its undocumented behavior is not modeled. */
    capacity = 264; memcpy(key + 4, &capacity, 4);
    CHECK(!xbox_XcPKEncPublic(key, input, output));
}

int main(void)
{
    unsigned char bad_sig[256], bad_hash[20], key[284];
    unsigned char synthetic[84] = {0}, block[64], output[80];
    ULONG h[5] = {0x31415352, 72, 512, 63, 1};
    static const unsigned char der[] = {0x30,0x21,0x30,0x09,0x06,0x05,0x2b,0x0e,0x03,0x02,0x1a,0x05,0,0x04,0x14};
    static const unsigned char der_short[] = {0x30,0x1f,0x30,0x07,0x06,0x05,0x2b,0x0e,0x03,0x02,0x1a,0x04,0x14};
    unsigned i, form;
    test_two_key_des();
    test_public_hardware_vectors();
    CHECK(xbox_XcPKGetKeyLen((PVOID)retail_key) == 264);
    CHECK(xbox_XcVerifyPKCS1Signature((PVOID)signature, (PVOID)retail_key, (PVOID)digest));
    memcpy(bad_sig, signature, sizeof bad_sig); bad_sig[123] ^= 1;
    CHECK(!xbox_XcVerifyPKCS1Signature(bad_sig, (PVOID)retail_key, (PVOID)digest));
    memcpy(bad_hash, digest, sizeof bad_hash); bad_hash[19] ^= 1;
    CHECK(!xbox_XcVerifyPKCS1Signature((PVOID)signature, (PVOID)retail_key, bad_hash));
    memcpy(key, retail_key, sizeof retail_key); key[88] ^= 1;
    CHECK(!xbox_XcVerifyPKCS1Signature((PVOID)signature, key, (PVOID)digest));
    CHECK(!xbox_XcVerifyPKCS1Signature(NULL, (PVOID)retail_key, (PVOID)digest));
    CHECK(!xbox_XcVerifyPKCS1Signature((PVOID)signature, NULL, (PVOID)digest));
    CHECK(!xbox_XcVerifyPKCS1Signature((PVOID)signature, (PVOID)retail_key, NULL));
    /* Exponent one isolates block validation; the retail vector above tests
     * actual 2048-bit RSA with exponent 65537 independently of this fixture. */
    memcpy(synthetic, h, sizeof h); memset(synthetic + 20, 0xff, 64);
    for (form = 0; form < 3; form++) {
        unsigned len = form == 0 ? 0 : form == 1 ? sizeof der : sizeof der_short;
        memset(block, 0xff, sizeof block); block[63] = 0; block[62] = 1;
        for (i = 0; i < 20; i++) block[i] = digest[19-i];
        for (i = 0; i < len; i++) block[20+i] = (form == 1 ? der : der_short)[len-1-i];
        block[20+len] = 0;
        CHECK(xbox_XcVerifyPKCS1Signature(block, synthetic, (PVOID)digest));
        block[61] = 0xfe;
        CHECK(!xbox_XcVerifyPKCS1Signature(block, synthetic, (PVOID)digest));
        block[61] = 0xff; block[20+len] = 0xff;
        CHECK(!xbox_XcVerifyPKCS1Signature(block, synthetic, (PVOID)digest));
    }
    memset(output, 0xa5, sizeof output);
    CHECK(xbox_XcPKEncPublic(synthetic, block, output));
    CHECK(!memcmp(output, block, 64));
    for (i = 64; i < 72; i++) CHECK(output[i] == 0);
    CHECK(output[72] == 0xa5);
    memset(block, 0xff, sizeof block);
    CHECK(!xbox_XcVerifyPKCS1Signature(block, synthetic, (PVOID)digest)); /* s == n */
    h[0] = 0; memcpy(synthetic, h, sizeof h);
    CHECK(!xbox_XcPKEncPublic(synthetic, block, output));
    h[0] = 0x31415352; h[2] = 0xffffffff; memcpy(synthetic, h, sizeof h);
    CHECK(!xbox_XcVerifyPKCS1Signature(block, synthetic, (PVOID)digest));
    printf("RSA/PKCS1 regression: %d failures\n", failures);
    return failures != 0;
}
