static void test_two_key_des(void)
{
    /* Independent reference: OpenSSL enc -des-ede[-cbc] -nopad,
     * key 0123456789abcdeffedcba9876543210, IV 1234567890abcdef. */
    static const UCHAR key[16] = {1,0x23,0x45,0x67,0x89,0xab,0xcd,0xef,0xfe,0xdc,0xba,0x98,0x76,0x54,0x32,0x10};
    static const UCHAR ecb[8] = {0x1a,0x4d,0x67,0x2d,0xca,0x6c,0xb3,0x35};
    static const UCHAR cbc[16] = {0x1a,0xab,0x6a,0xcb,0xa5,0xab,0xd5,0x44,0x7f,3,0x5a,0x8e,0x9e,0x27,0xbb,0x1d};
    static const UCHAR iv[8] = {0x12,0x34,0x56,0x78,0x90,0xab,0xcd,0xef};
    UCHAR table[384], out[16], plain[16], feedback[8];
    UCHAR *pages = VirtualAlloc(NULL, 8192, MEM_RESERVE | MEM_COMMIT, PAGE_READWRITE);
    DWORD old;
    CHECK(pages != NULL);
    if (!pages) return;
    CHECK(VirtualProtect(pages + 4096, 4096, PAGE_NOACCESS, &old));
    memcpy(pages + 4096 - sizeof key, key, sizeof key);
    /* Reading K3 after a 16-byte key faults here; K3 must reuse K1. */
    xbox_XcKeyTable(1, table, pages + 4096 - sizeof key);
    xbox_XcBlockCrypt(1, out, (PVOID)key, table, 1);
    CHECK(!memcmp(out, ecb, sizeof ecb));
    xbox_XcBlockCrypt(1, plain, out, table, 0);
    CHECK(!memcmp(plain, key, 8));
    memcpy(feedback, iv, sizeof iv);
    xbox_XcBlockCryptCBC(1, sizeof key, out, (PVOID)key, table, 1, feedback);
    CHECK(!memcmp(out, cbc, sizeof cbc));
    CHECK(!memcmp(feedback, cbc + 8, 8));
    memcpy(feedback, iv, sizeof iv);
    xbox_XcBlockCryptCBC(1, sizeof key, out, out, table, 0, feedback);
    CHECK(!memcmp(out, key, sizeof key));
    CHECK(!memcmp(feedback, cbc + 8, 8));
    VirtualFree(pages, 0, MEM_RELEASE);
}
